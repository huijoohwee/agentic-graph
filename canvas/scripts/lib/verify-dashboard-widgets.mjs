import assert from 'node:assert/strict'

export async function verifyFullCanvas(page) {
  const pane = await page.getByRole('region', { name: 'Canvas pane', exact: true }).boundingBox()
  const viewport = await page.locator('[data-kg-canvas-viewport-root="1"]').boundingBox()
  const container = await page.locator('[data-kg-canvas-view-container="full"]').boundingBox()
  assert.ok(pane && viewport && Math.abs(pane.x - viewport.x) < 1 && Math.abs(pane.y - viewport.y) < 1
    && Math.abs(pane.width - viewport.width) < 1 && Math.abs(pane.height - viewport.height) < 1,
    'Every renderer must fill the shared canvas beneath workspace overlays')
  assert.ok(container && Math.abs(container.x - pane.x) < 1 && Math.abs(container.width - pane.width) < 1,
    'Full sizing is the default for the shared renderer container')
}

export async function verifyAgentMissionSourceFiles(page, authoredSnapshot, assertAuthored) {
  await page.evaluate(async () => (await import('/src/hooks/useGraphStore.ts')).useGraphStore.getState().setWorkspaceViewState({ mode: 'editor', paneOpen: false }))
  const shell = page.getByRole('region', { name: 'Markdown Workspace', exact: true })
  // The first native Editor mount loads its module graph on a cold CI server.
  await shell.waitFor({ state: 'visible', timeout: 60000 })
  await shell.getByRole('checkbox', { name: 'Show Explorer pane', exact: true }).check()
  const files = shell.getByRole('region', { name: 'Source Files content', exact: true })
  await files.getByRole('button', { name: 'Folder agent-mission', exact: true }).waitFor()
  await files.getByRole('button', { name: 'Folder docs', exact: true }).waitFor()
  await verifyFullCanvas(page)
  const before = await authoredSnapshot()
  await files.getByRole('button', { name: 'File agent-mission.manifest.json', exact: true }).click()
  const editor = page.getByRole('region', { name: 'Markdown Workspace', exact: true })
  assert.equal(await page.getByRole('region', { name: 'Markdown Workspace', exact: true }).count(), 1)
  assert.equal(await page.getByText('Agent observability', { exact: true }).count(), 0)
  await editor.getByRole('button', { name: 'Folder docs', exact: true }).waitFor()
  await editor.getByRole('checkbox', { name: 'Show JSON editor pane', exact: true }).check()
  await editor.getByRole('region', { name: 'JSON Editor', exact: true }).getByText('agent-run-inspection/v1', { exact: false }).waitFor()
  await verifyFullCanvas(page)
  await editor.getByRole('button', { name: 'Close', exact: true }).click()
  await page.getByRole('region', { name: 'Dashboard', exact: true }).getByRole('button', { name: 'Close run inspection', exact: true }).click()
  await files.getByRole('button', { name: 'Folder agent-mission', exact: true }).waitFor()
  assertAuthored(await authoredSnapshot(), before, 'Manifest inspection must preserve the active authored source')
  await editor.getByRole('button', { name: 'Close', exact: true }).click()
  const persisted = await page.evaluate(async () => (await (await import('/src/features/workspace-fs/workspaceFs.ts')).getWorkspaceFs()).listEntries())
  assert.equal(persisted.some(entry => entry.path.startsWith('/agent-mission/')), false, 'Session evidence must not enter persistent Source Files')
}

async function configureWidget(frame, keyboard = false) {
  if (keyboard) await frame.press('Enter')
  else await frame.click()
  assert.equal(await frame.getByRole('form', { name: 'Widget configuration' }).count(), 0, 'Selection must reveal actions, not configuration')
  const toolbar = frame.locator('nav.kg-dashboard-widget-toolbar[data-kg-bubble-toolbar="1"]')
  await toolbar.waitFor()
  const flip = toolbar.getByRole('button', { name: 'Flip to configure', exact: true })
  if (keyboard) await flip.press('Enter')
  else await flip.locator('[data-kg-toolbar-action-icon="flip"]').click()
  await frame.locator('section.kg-dashboard-widget-face[data-kg-widget-face="back"]').waitFor()
}

/** Templates and placed cards use one configuration back in the original Props palette. */
export async function verifyDashboardWidgets(page) {
  const dashboard = page.getByRole('region', { name: 'Dashboard', exact: true })
  assert.equal(await dashboard.locator('[data-kg-dashboard-canvas]').count(), 1)
  assert.equal(await page.locator('#canvas-dashboard-mission-panel, #canvas-dashboard-graph-panel').count(), 0)
  assert.equal(await dashboard.locator('[data-kg-dashboard-card="agent-tree"]').count(), 1)
  assert.equal(await dashboard.getByRole('button', { name: 'Props Panel', exact: true }).count(), 0)
  await page.getByRole('button', { name: 'Create Node', exact: true }).click()
  const floating = page.locator('[data-kg-floating-panel-root="true"]')
  await floating.getByRole('region', { name: 'Props Panel', exact: true }).waitFor()
  assert.equal(await floating.count(), 1)
  await floating.locator('[data-kg-floating-panel-view-trigger="media"]').waitFor()
  const palette = page.getByRole('complementary', { name: 'Widget palette', exact: true })
  for (const title of ['Widget Card Type 0', 'Probe-Tree Type 1', 'Probe-Tree Type 2', 'Deliverables Widget Card', 'Rich Media Panel']) await palette.getByText(title, { exact: true }).waitFor()
  assert.equal(await palette.getByRole('listitem', { name: /^Template / }).count(), 6)
  assert.equal(await palette.getByRole('form', { name: 'Widget configuration' }).count(), 0, 'Fronts contain no configuration')
  assert.equal(await palette.getByText('Relationship Types', { exact: true }).count(), 0, 'Template fronts must be unbound')
  const tree = palette.getByRole('listitem', { name: 'Template Span tree', exact: true })
  await configureWidget(tree.getByRole('group', { name: 'Configure Span tree', exact: true }))
  await tree.getByRole('button', { name: 'Remove widget', exact: true }).click()
  await dashboard.locator('[data-kg-dashboard-card="agent-tree"]').waitFor({ state: 'detached' })
  await configureWidget(tree.getByRole('group', { name: 'Configure Span tree', exact: true }))
  await tree.getByLabel('Show on canvas', { exact: true }).check()
  await tree.getByRole('button', { name: 'Save widget', exact: true }).click()
  await dashboard.locator('[data-kg-dashboard-card="agent-tree"]').waitFor()
  const template = palette.getByRole('listitem', { name: 'Template Bar chart', exact: true })
  const templateFront = template.getByRole('group', { name: 'Configure Bar chart', exact: true })
  const templateSize = await templateFront.boundingBox()
  await configureWidget(templateFront)
  const templateBackSize = await templateFront.boundingBox()
  assert.equal(templateBackSize.width, templateSize.width)
  assert.equal(templateBackSize.height, templateSize.height, 'Flipping a template must preserve its dimensions')
  await template.getByLabel('Widget', { exact: true }).selectOption('graph:node-types')
  await template.getByLabel('Title', { exact: true }).fill('My node types')
  await template.getByLabel('Display', { exact: true }).selectOption('table')
  await template.getByRole('button', { name: 'Save widget', exact: true }).click()
  const card = dashboard.getByRole('group', { name: 'Dashboard card My node types', exact: true })
  await card.waitFor()
  assert.equal(await card.getByRole('img', { name: 'Dashboard bar chart' }).count(), 0)
  // Close the overlay before interacting with the full Canvas behind it.
  await floating.getByRole('button', { name: 'Close', exact: true }).click()
  const cardFrame = dashboard.getByRole('group', { name: 'Configure My node types', exact: true })
  const cardSize = await cardFrame.boundingBox()
  await configureWidget(cardFrame, true)
  const cardBackSize = await cardFrame.boundingBox()
  assert.equal(cardBackSize.width, cardSize.width)
  assert.equal(cardBackSize.height, cardSize.height, 'Flipping a placed card must preserve its dimensions')
  const back = dashboard.getByRole('form', { name: 'Widget configuration', exact: true })
  await back.getByLabel('Title', { exact: true }).fill('Node Types')
  await back.getByLabel('Display', { exact: true }).selectOption('bar')
  await back.getByRole('button', { name: 'Save widget', exact: true }).click()
  await dashboard.getByRole('group', { name: 'Dashboard card Node Types', exact: true }).waitFor()
  await page.getByRole('button', { name: 'Create Node', exact: true }).click()
  const metric = palette.getByRole('listitem', { name: 'Template Metric', exact: true })
  const metricFrame = metric.getByRole('group', { name: 'Configure Metric', exact: true })
  const metricSize = await metricFrame.boundingBox()
  await configureWidget(metricFrame)
  const metricBackSize = await metricFrame.boundingBox()
  assert.equal(metricBackSize.width, metricSize.width)
  assert.equal(metricBackSize.height, metricSize.height, 'Compact metric backs must scroll within the original size')
  await metric.getByLabel('Data source', { exact: true }).selectOption('graph:nodes')
  await metric.getByLabel('Title', { exact: true }).fill('My metric')
  await metric.getByRole('button', { name: 'Add widget', exact: true }).click()
  await dashboard.getByRole('group', { name: 'Configure My metric', exact: true }).waitFor()
  assert.equal(await dashboard.locator('[data-kg-dashboard-metric]').count(), 6)
  await configureWidget(metricFrame)
  await metric.getByLabel('Widget', { exact: true }).selectOption({ label: 'My metric' })
  await metric.getByRole('button', { name: 'Remove widget', exact: true }).click()
  await dashboard.getByRole('group', { name: 'Configure My metric', exact: true }).waitFor({ state: 'detached' })
  const source = await page.evaluate(async () => (await (await import('/src/features/workspace-fs/workspaceFs.ts')).getWorkspaceFs()).readFileText('/notes/dashboard.widgets.json'))
  assert.equal(JSON.parse(source).widgets['graph:node-types'].title, 'Node Types')
  assert.equal(source.includes('agent-run-inspection/v1'), false)
  await floating.getByRole('button', { name: 'Close', exact: true }).click()
  console.log('Original Props card types, generic templates, shared selectable toolbar and fixed-size flip configuration CRUD passed')
}
