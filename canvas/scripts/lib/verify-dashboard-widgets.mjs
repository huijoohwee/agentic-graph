import assert from 'node:assert/strict'

/** CRUD uses the existing visual Props palette and inline Dashboard editors. */
export async function verifyDashboardWidgets(page) {
  const dashboard = page.getByRole('region', { name: 'Dashboard', exact: true })
  await dashboard.getByRole('tab', { name: 'Graph statistics', exact: true }).click()
  await dashboard.getByRole('button', { name: 'Props Panel', exact: true }).click()
  const palette = page.getByRole('complementary', { name: 'Widget palette', exact: true })
  const entry = palette.getByRole('listitem', { name: 'Widget graph:node-types', exact: true })
  await entry.getByRole('region', { name: 'Dashboard card title for node-types', exact: true }).dblclick()
  await entry.getByRole('textbox', { name: 'Dashboard card title for node-types', exact: true }).fill('My node types')
  await entry.getByRole('textbox', { name: 'Dashboard card title for node-types', exact: true }).press('Enter')
  const card = dashboard.getByRole('group', { name: 'Dashboard card My node types', exact: true })
  await card.waitFor()
  await entry.getByLabel('Display graph:node-types', { exact: true }).selectOption('table')
  await card.getByRole('img', { name: 'Dashboard bar chart' }).waitFor({ state: 'detached' })
  await entry.getByRole('button', { name: 'Remove widget', exact: true }).click()
  await card.waitFor({ state: 'detached' })
  await entry.getByRole('button', { name: 'Show widget', exact: true }).click()
  await card.waitFor()
  await entry.getByRole('region', { name: 'Dashboard card title for node-types', exact: true }).dblclick()
  await entry.getByRole('textbox', { name: 'Dashboard card title for node-types', exact: true }).fill('Node Types')
  await entry.getByRole('textbox', { name: 'Dashboard card title for node-types', exact: true }).press('Enter')
  await entry.getByLabel('Display graph:node-types', { exact: true }).selectOption('bar')
  await dashboard.getByRole('group', { name: 'Dashboard card Node Types', exact: true }).waitFor()
  await palette.getByRole('listitem', { name: 'Widget graph:nodes', exact: true }).getByRole('button', { name: 'Add widget', exact: true }).click()
  const custom = palette.getByRole('listitem', { name: /^Widget graph:widget-/ })
  await custom.waitFor()
  assert.equal(await dashboard.locator('[data-kg-dashboard-metric]').count(), 6)
  await custom.getByRole('button', { name: 'Remove widget', exact: true }).click()
  await custom.waitFor({ state: 'detached' })
  const source = await page.evaluate(async () => (await (await import('/src/features/workspace-fs/workspaceFs.ts')).getWorkspaceFs()).readFileText('/notes/dashboard.widgets.json'))
  assert.equal(JSON.parse(source).widgets['graph:node-types'].title, 'Node Types')
  assert.equal(source.includes('agent-run-inspection/v1'), false)
  await page.locator('[data-kg-floating-panel-root="true"]').getByRole('button', { name: 'Close', exact: true }).click()
  await dashboard.getByRole('tab', { name: 'Agent Mission', exact: true }).click()
  console.log('Existing Props palette widget CRUD and Source Files configuration passed')
}
