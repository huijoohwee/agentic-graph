import assert from 'node:assert/strict'
import { importWorkspaceUrl } from '@/features/markdown-workspace/workspaceImport/urlImport'
import { createMemoryWorkspaceFs } from '@/features/workspace-fs/workspaceFsMemory'
import { planWebsiteCollectionConsolidation } from '@/features/workspace-fs/websiteCollections'
import { setWorkspaceEntrySource } from '@/features/workspace-fs/sourceIndex'
import { resolveWebsiteImportNodeRelativeDocumentPath, websiteSourceBundlePath } from '@/lib/websites/websitePathUtils'

export async function testVideoSourceLocations() {
  const fs = createMemoryWorkspaceFs()
  const url = new URL('/media/recording.mp4?revision=2', 'https://media.example.test').href
  const direct = { name: 'recording.mp4.source.md', normalizedUrl: url, text: '# Recording', sourceMimeHint: 'video/mp4', sourceMediaKind: 'video' as const }
  const options = { fs, urlRaw: url, mirrorToHost: false, fetchUrlContent: async () => direct }
  const first = await importWorkspaceUrl(options)
  const folder = websiteSourceBundlePath(url)
  assert.equal(first.createdPaths[0], folder + '/recording.video-sequence.timeline.md')
  const hostRoot = folder.slice(0, folder.lastIndexOf('/'))
  const pageDir = await fs.createFolder({ parentPath: hostRoot, name: 'media' })
  const legacyPage = await fs.createFile({ parentPath: pageDir,
    name: resolveWebsiteImportNodeRelativeDocumentPath({ nodeUrl: url }).split('/').pop()!,
    text: `---\nkgWebpageUrl: "${url}"\n---\nA previous capture` })
  setWorkspaceEntrySource(legacyPage, { kind: 'url', url, importState: { identity: 'url:' + url, outputDigest: '', checkedAt: 1, status: 'imported' } })
  const repeat = await importWorkspaceUrl({ ...options, fetchUrlContent: async () => { throw Error('Unexpected fetch') } })
  assert.deepEqual(repeat.createdPaths, first.createdPaths)
  assert(!((await fs.listEntries()).some(row => row.name === direct.name)))
  assert.notEqual(websiteSourceBundlePath(url.replace('revision=2', 'revision=3')), folder)

  // Rebuild a dated conversion offline and retire it only after every generated byte is accounted for.
  const converted = { ...direct, name: 'converted.md', text: 'A saved transcript', sourceMimeHint: 'text/markdown',
    transcriptJsonText: JSON.stringify({ segments: [{ start: 0, duration: 4, text: 'A saved transcript' }] }) }
  const original = createMemoryWorkspaceFs()
  const imported = await importWorkspaceUrl({ ...options, fs: original, fetchUrlContent: async () => converted })
  const initialOffline = await importWorkspaceUrl({ ...options, fs: original, fetchUrlContent: async () => { throw Error('Cannot fetch offline') } })
  assert.deepEqual(initialOffline.createdPaths, imported.createdPaths)
  const path = imported.createdPaths[0]!
  const oldRoot = '/docs_/20260101T010203Z'
  const legacyRows = (await original.listEntries()).filter(row => row.path === folder || row.parentPath === folder)
    .map(row => ({ ...row, path: row.path.replace(folder, oldRoot), parentPath: row.path === folder ? '/docs_' : oldRoot,
      text: row.text?.replaceAll(folder, oldRoot).replace('\n    workspaceRoot: "/websites"\n', '\n    workspaceRoot: "/docs_"\n') }))
  const fsWithHistory = createMemoryWorkspaceFs({ initialEntries: legacyRows })
  const legacyPath = path.replace(folder, oldRoot)
  setWorkspaceEntrySource(legacyPath, { kind: 'url', url, importState: { identity: 'url:' + url, outputDigest: '', checkedAt: 1, status: 'imported' } })
  const migrated = await importWorkspaceUrl({ ...options, fs: fsWithHistory, fetchUrlContent: async () => { throw Error('Legacy bytes must work offline') } })
  assert.equal(migrated.createdPaths[0], path)
  const offline = await importWorkspaceUrl({ ...options, fs: fsWithHistory, fetchUrlContent: async () => { throw Error('Cannot fetch offline') } })
  assert.deepEqual(offline.createdPaths, migrated.createdPaths)
  const entries = await fsWithHistory.listEntries()
  const plan = planWebsiteCollectionConsolidation(entries)
  assert.equal(plan.moved.get(legacyPath), path)
  assert(!plan.entries.some(row => row.path.startsWith(oldRoot + '/')))
  const edited = entries.map(row => row.path === oldRoot + '/render.html' ? { ...row, text: 'Local edit' } : row)
  assert.equal(planWebsiteCollectionConsolidation(edited).moved.size, 0)
  await fsWithHistory.writeFileText(folder + '/render.html', 'Retained edit')
  await assert.rejects(importWorkspaceUrl({ ...options, fs: fsWithHistory, documentSemanticMode: 'document',
    fetchUrlContent: async () => converted }), /conflict/i)
  assert.equal(await fsWithHistory.readFileText(folder + '/render.html'), 'Retained edit')
}
